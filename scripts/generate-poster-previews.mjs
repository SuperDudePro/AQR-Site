// Generates small web previews (WebP, max 1200px) from the full-res poster masters,
// and writes src/posterPreviews.ts mapping each master png URL -> its preview URL.
//
// Why: the site was serving 20-26 MB print masters (3600x5400) as on-page <img>.
// Previews are ~100-250 KB, so page weight and Vercel bandwidth drop ~100x. Download
// links still point at the full-res masters.
//
// Run once (or whenever posters change):  node scripts/generate-poster-previews.mjs

import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..");
const PUBLIC = join(ROOT, "public");
const OUT_DIR = join(PUBLIC, "posters", "previews");
const DATA = readFileSync(join(ROOT, "src", "posterData.ts"), "utf8");

const MAX_WIDTH = 1200;
const QUALITY = 78;

mkdirSync(OUT_DIR, { recursive: true });

// Unique png URLs as they appear in the data (may be URL-encoded, e.g. %20).
const pngUrls = [...new Set([...DATA.matchAll(/"(\/posters\/[^"]+\.png)"/g)].map((m) => m[1]))];

function slugify(name) {
  return name
    .replace(/\.png$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

const map = {};
let made = 0;
let skipped = 0;

for (const url of pngUrls) {
  // The data stores URL-encoded paths; the file on disk is the decoded name.
  const diskRel = decodeURIComponent(url);
  const srcPath = join(PUBLIC, diskRel);
  const previewName = `${slugify(basename(diskRel))}.webp`;
  const previewUrl = `/posters/previews/${previewName}`;
  const outPath = join(OUT_DIR, previewName);

  if (!existsSync(srcPath)) {
    console.warn(`  skip (master missing): ${diskRel}`);
    skipped += 1;
    continue; // no map entry -> component falls back to the master
  }

  await sharp(srcPath)
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .webp({ quality: QUALITY })
    .toFile(outPath);

  map[url] = previewUrl;
  made += 1;
}

const entries = Object.entries(map)
  .map(([png, preview]) => `  ${JSON.stringify(png)}: ${JSON.stringify(preview)},`)
  .join("\n");

const ts = `// AUTO-GENERATED by scripts/generate-poster-previews.mjs — do not edit by hand.
// Maps each full-res poster master (png URL) to its small web preview (webp URL).

const POSTER_PREVIEWS: Record<string, string> = {
${entries}
};

// Returns the web preview for a master png, or the master itself if no preview exists.
export function posterPreview(png: string): string {
  return POSTER_PREVIEWS[png] ?? png;
}
`;

writeFileSync(join(ROOT, "src", "posterPreviews.ts"), ts);

const totalBytes = Object.values(map).reduce((sum, url) => {
  const p = join(PUBLIC, url);
  return sum + (existsSync(p) ? statSync(p).size : 0);
}, 0);

console.log(`Previews generated: ${made} (skipped ${skipped}).`);
console.log(`Total preview weight: ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
console.log(`Wrote src/posterPreviews.ts (${Object.keys(map).length} entries).`);
